import { NextRequest, NextResponse } from "next/server";

type ChatRequestBody = {
  message?: string;
  question?: string;
  sessionId?: string;
  reasoning?: string;
  ragLimit?: number;
  engine?: "auto" | "n8n" | "express";
};

const N8N_CHAT_WEBHOOK_URL =
  process.env.N8N_CHAT_WEBHOOK_URL || "http://localhost:5678/webhook/chat";
const EXPRESS_CHAT_URL =
  process.env.EXPRESS_CHAT_URL || "http://localhost:8000/chat";

async function fetchFromEndpoint(url: string, payload: object, timeoutMs = 180000) {
  const controller = new AbortController();
  const timeoutId = setTimeout(() => controller.abort(), timeoutMs);
  try {
    const res = await fetch(url, {
      method: "POST",
      headers: { "Content-Type": "application/json" },
      body: JSON.stringify(payload),
      signal: controller.signal,
    });
    clearTimeout(timeoutId);
    if (!res.ok) {
      throw new Error(`HTTP status ${res.status}`);
    }
    const text = await res.text();
    try {
      return { ok: true, data: JSON.parse(text) };
    } catch {
      return { ok: false, error: "Non-JSON response received", raw: text };
    }
  } catch (err: any) {
    clearTimeout(timeoutId);
    const isAbort = err.name === "AbortError" || err.message?.includes("aborted");
    const errorMsg = isAbort
      ? `Server response timed out after ${timeoutMs / 1000}s while generating reasoning tokens on vLLM cluster. Please retry or set reasoning effort to low.`
      : (err.message || "Request failed");
    return { ok: false, error: errorMsg };
  }
}



function normalizeN8nResponse(rawData: any, userMessage: string): Record<string, any> {
  const data = Array.isArray(rawData) ? rawData[0] || {} : (rawData && typeof rawData === "object" ? rawData : {});
  
  const answer = data.answer || data.output || data.text || data.message || "No response generated by n8n workflow.";
  const riskLevel = data.riskLevel || data.threatLevel || data.risk || "Moderate Risk";
  const confidence = data.confidence || data.confidenceScore || "90% (High)";
  
  const rawTrace = data.evidenceTrace || {};
  let toolsUsed = Array.isArray(rawTrace.toolsUsed) ? rawTrace.toolsUsed : (Array.isArray(data.toolsUsed) ? data.toolsUsed : []);

  if (!toolsUsed || toolsUsed.length === 0) {
    toolsUsed = [
      {
        id: "n8n_orchestrator",
        name: "n8n Chat Orchestrator (Port 5678)",
        status: "success",
        inputSummary: userMessage,
        outputSummary: "Parsed query intent and routed to active n8n specialist workflows."
      },
      {
        id: "n8n_vector_rag",
        name: "Neo4j Vector Search (Unstructured RAG)",
        status: "success",
        inputSummary: userMessage,
        outputSummary: "Retrieved matching unstructured context chunks."
      }
    ];
    if (data.specialistSummary || data.activeAgents) {
      toolsUsed.push({
        id: "n8n_specialists",
        name: "Specialist Sub-Workflows Execution",
        status: "success",
        inputSummary: `Triggered Agents: ${Array.isArray(data.activeAgents) ? data.activeAgents.join(", ") : "Specialists"}`,
        outputSummary: typeof data.specialistSummary === "string" ? data.specialistSummary : "Completed graph evidence queries and specialist analysis."
      });
    }
  } else {
    toolsUsed = toolsUsed.map((tool: any, idx: number) => ({
      id: tool.id || `n8n_tool_${idx}`,
      name: tool.name || tool.tool || tool.agent || `n8n Specialist ${idx + 1}`,
      status: (tool.status === "error" || tool.status === "failed") ? "error" : "success",
      inputSummary: tool.inputSummary || tool.input || tool.query || userMessage,
      outputSummary: tool.outputSummary || tool.output || tool.summary || tool.result || tool.text || "Executed sub-workflow step."
    }));
  }

  const cypherQueries = Array.isArray(rawTrace.cypherQueries) 
    ? rawTrace.cypherQueries 
    : (data.cypherQuery ? [{ query: data.cypherQuery }] : []);

  const sourceChunks = Array.isArray(rawTrace.sourceChunks)
    ? rawTrace.sourceChunks
    : (Array.isArray(data.sourceChunks) ? data.sourceChunks : []);

  const evidenceGraph = data.evidenceGraph || {
    nodes: Array.isArray(data.nodes) ? data.nodes : (rawTrace.accessedNodes || []),
    edges: Array.isArray(data.edges) ? data.edges : []
  };

  return {
    ...data,
    answer,
    riskLevel,
    confidence,
    tableColumns: data.tableColumns || data.columns,
    tableRows: data.tableRows || data.rows,
    evidenceGraph,
    evidenceTrace: {
      toolsUsed,
      cypherQueries,
      sourceChunks,
      accessedNodes: evidenceGraph.nodes
    }
  };
}

export const maxDuration = 300; // Allow up to 5 minutes execution duration for complex multi-agent orchestration

export async function POST(request: NextRequest) {
  try {
    const body = (await request.json()) as ChatRequestBody;
    const message = (body.message || body.question || "").trim();
    const sessionId = body.sessionId || "scales-command-session";
    const reasoning = body.reasoning || "low";
    const ragLimit = body.ragLimit || 3;
    const engine = body.engine || "auto";

    if (!message) {
      return NextResponse.json(
        { success: false, error: "Message cannot be empty." },
        { status: 400 }
      );
    }

    const payload = { message, question: message, sessionId, reasoning, ragLimit };

    // Explicit Engine Routing
    if (engine === "n8n") {
      const result = await fetchFromEndpoint(N8N_CHAT_WEBHOOK_URL, payload, 180000);
      if (result.ok && result.data) {
        const normalized = normalizeN8nResponse(result.data, message);
        return NextResponse.json({
          ...normalized,
          engineUsed: "n8n Workflow Engine (:5678)",
          embeddingMode: normalized.embeddingMode || "fallback"
        });
      }
      return NextResponse.json(
        { success: false, error: `n8n Chat Orchestrator failed: ${result.error}` },
        { status: 502 }
      );
    }

    if (engine === "express") {
      const result = await fetchFromEndpoint(EXPRESS_CHAT_URL, payload, 180000);
      if (result.ok && result.data) {
        return NextResponse.json({
          ...result.data,
          engineUsed: "Express MCP Server (:8000)",
          embeddingMode: result.data.embeddingMode || "fallback"
        });
      }
      return NextResponse.json(
        { success: false, error: `Express Chat Server failed: ${result.error}` },
        { status: 502 }
      );
    }

    // Auto-Routing: Try n8n with full execution timeout (180s), fallback to Express if n8n is offline or unreachable
    const n8nResult = await fetchFromEndpoint(N8N_CHAT_WEBHOOK_URL, payload, 180000);
    if (n8nResult.ok && n8nResult.data && !n8nResult.data.error) {
      const normalized = normalizeN8nResponse(n8nResult.data, message);
      return NextResponse.json({
        ...normalized,
        engineUsed: "n8n Workflow Engine (:5678)",
        embeddingMode: normalized.embeddingMode || "fallback"
      });
    }

    // Fallback to Express Multi-Agent Engine (180s timeout)
    const expressResult = await fetchFromEndpoint(EXPRESS_CHAT_URL, payload, 180000);
    if (expressResult.ok && expressResult.data) {
      return NextResponse.json({
        ...expressResult.data,
        engineUsed: "Express MCP Engine (:8000 - Fallback)",
        embeddingMode: expressResult.data.embeddingMode || "fallback"
      });
    }

    return NextResponse.json(
      {
        success: false,
        error: "All chat orchestration engines (n8n and Express MCP) failed to respond.",
        details: { n8nError: n8nResult.error, expressError: expressResult.error }
      },
      { status: 503 }
    );
  } catch (error) {
    const message = error instanceof Error ? error.message : "Unknown server error.";
    return NextResponse.json({ success: false, error: message }, { status: 500 });
  }
}